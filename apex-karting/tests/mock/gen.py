#!/usr/bin/env python3
"""Generates the inputs for the mock Roblox runtime.

1. gen/api.luau   - classes (members + types) and enums parsed from luau-lsp's
                    Roblox definitions, so the mock rejects unknown properties.
2. gen/<path>.luau - every game script wrapped as `return function(env) ... end`
                    so it runs with the mock globals (game, script, Vector3...).

Run from the project root:  python3 tests/mock/gen.py /path/to/globalTypes.d.luau
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "tests", "mock", "gen")
DEFS = sys.argv[1] if len(sys.argv) > 1 else "/root/tools/globalTypes.d.luau"

os.makedirs(OUT, exist_ok=True)

# ---------------------------------------------------------------- API
classes, enums = {}, {}
cur = None
for line in open(DEFS, encoding="utf-8"):
    m = re.match(r"declare extern type (\w+)(?: extends (\w+))? with", line)
    if m:
        name, sup = m.group(1), m.group(2)
        if name.endswith("_INTERNAL") and name.startswith("Enum"):
            cur = ("enum", name[4:-9])
            enums[cur[1]] = []
        else:
            cur = ("class", name)
            classes[name] = {"super": sup, "props": {}, "methods": []}
        continue
    if line.startswith("end"):
        cur = None
        continue
    if not cur:
        continue
    s = line.strip()
    if s.startswith("@"):
        continue
    if cur[0] == "enum":
        m = re.match(r"(\w+): Enum\w+", s)
        if m:
            enums[cur[1]].append(m.group(1))
    else:
        m = re.match(r"function (\w+)\(", s)
        if m:
            classes[cur[1]]["methods"].append(m.group(1))
            continue
        m = re.match(r"(\w+): (.+)$", s)
        if m:
            classes[cur[1]]["props"][m.group(1)] = m.group(2)

def lua_str(s):
    return json.dumps(s)

with open(os.path.join(OUT, "api.luau"), "w") as f:
    f.write("-- generated by tests/mock/gen.py\nreturn {\n\tclasses = {\n")
    for name, c in classes.items():
        f.write("\t\t[%s] = { super = %s, props = {" % (lua_str(name), lua_str(c["super"]) if c["super"] else "nil"))
        f.write(", ".join("[%s] = %s" % (lua_str(k), lua_str(v)) for k, v in c["props"].items()))
        f.write("}, methods = {")
        f.write(", ".join("[%s] = true" % lua_str(k) for k in c["methods"]))
        f.write("} },\n")
    f.write("\t},\n\tenums = {\n")
    for name, items in enums.items():
        f.write("\t\t[%s] = { %s },\n" % (lua_str(name), ", ".join(lua_str(i) for i in items)))
    f.write("\t},\n}\n")

# ---------------------------------------------------------------- scripts
GLOBALS = ["game", "workspace", "script", "Instance", "Vector3", "Vector2", "CFrame", "Color3",
           "UDim", "UDim2", "Enum", "PhysicalProperties", "Region3", "RaycastParams", "TweenInfo", "Font",
           "NumberSequence", "NumberSequenceKeypoint", "ColorSequence", "ColorSequenceKeypoint", "NumberRange",
           "task", "require", "print", "warn", "os", "vector", "typeof", "tick", "Random", "DateTime"]

def wrap(src, rel):
    # `export type` is only legal at the top level; inside the wrapper it is a local type
    src = re.sub(r"^export type ", "type ", src, flags=re.M)
    head = "-- generated from %s by tests/mock/gen.py\nreturn function(env)\n" % rel
    head += "local %s = %s\n" % (", ".join(GLOBALS), ", ".join("env.%s" % g for g in GLOBALS))
    return head + src + "\nend\n"

count = 0
keys = []
for base, _, files in os.walk(os.path.join(ROOT, "src")):
    for fn in files:
        if not fn.endswith(".luau"):
            continue
        path = os.path.join(base, fn)
        rel = os.path.relpath(path, ROOT)
        key = rel.replace(os.sep, "_").replace(".", "_")
        with open(path, encoding="utf-8") as fh:
            src = fh.read()
        with open(os.path.join(OUT, key + ".luau"), "w") as fh:
            fh.write(wrap(src, rel))
        keys.append(key)
        count += 1
# index of all wrapped scripts (static requires)
with open(os.path.join(OUT, "index.luau"), "w") as fh:
    fh.write("-- generated by tests/mock/gen.py\nreturn {\n")
    for k in sorted(keys):
        fh.write('\t%s = require("./%s"),\n' % (k, k))
    fh.write("}\n")
print("api: %d classes, %d enums; wrapped %d scripts" % (len(classes), len(enums), count))
